#!/usr/bin/env bash
# Pack the current tree exactly as npm would publish it, install the tarball
# cleanly under $QA_DIR/rc, and write $QA_DIR/rc/run.sh: an ACP launcher that
# records the wire (client->agent in.ndjson, agent->client out.ndjson) and
# stderr into the log directory given as its first argument (default
# $QA_DIR/logs/gui). GUI apps do not load nvm, so run.sh uses absolute paths.
#
# Usage: pack-rc.sh <QA_DIR>
set -euo pipefail
QA_DIR=${1:?usage: pack-rc.sh <QA_DIR>}
REPO=$(git rev-parse --show-toplevel)
NODE=$(command -v node)
mkdir -p "$QA_DIR/rc" "$QA_DIR/logs"
(cd "$REPO" && npm run build >/dev/null)
rm -f "$QA_DIR"/rc/*.tgz
TGZ=$(cd "$REPO" && npm pack --pack-destination "$QA_DIR/rc" 2>/dev/null | tail -1)
(
  cd "$QA_DIR/rc"
  [ -f package.json ] || npm init -y >/dev/null
  rm -rf node_modules package-lock.json
  npm install --no-audit --no-fund "./$TGZ" >/dev/null
)
ENTRY="$QA_DIR/rc/node_modules/@bex-co/muse-code-acp/dist/index.js"
[ -f "$ENTRY" ] || { echo "pack-rc: installed entry missing: $ENTRY" >&2; exit 1; }
cat > "$QA_DIR/rc/run.sh" <<RUN
#!/bin/bash
# Generated by pack-rc.sh. Records the ACP wire and stderr; never alters them.
D=\${1:-$QA_DIR/logs/gui}
mkdir -p "\$D"
tee -a "\$D/in.ndjson" | "$NODE" "$ENTRY" 2>>"\$D/stderr.log" | tee -a "\$D/out.ndjson"
RUN
chmod +x "$QA_DIR/rc/run.sh"
VERSION=$("$NODE" -p "require('$QA_DIR/rc/node_modules/@bex-co/muse-code-acp/package.json').version")
echo "{\"tarball\":\"$TGZ\",\"version\":\"$VERSION\",\"commit\":\"$(cd "$REPO" && git rev-parse --short HEAD)\",\"dirty\":$( [ -n "$(cd "$REPO" && git status --porcelain)" ] && echo true || echo false),\"entry\":\"$ENTRY\",\"run\":\"$QA_DIR/rc/run.sh\"}" | tee "$QA_DIR/rc/rc.json"
